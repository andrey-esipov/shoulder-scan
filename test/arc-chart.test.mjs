import assert from 'node:assert/strict';
import { ArcChart, clusterMarkers } from '../js/arc-chart.js';

globalThis.window = { devicePixelRatio: 1, addEventListener() {} };
globalThis.requestAnimationFrame = () => 1;
const chart = new ArcChart({ getContext: () => null, getBoundingClientRect: () => ({ width: 300, height: 80 }) });
chart.push(1, 150, 100);
chart.push(1.05, 12, -30);
assert.equal(chart.data.at(-2).e, null, 'a loop jump starts a new trace segment');
assert.equal(chart.data.at(-1).r, -30, 'rotation smoothing must not bridge a restart');
chart.breakLine(2);
chart.push(2.05, 20, 40);
assert.equal(chart.data.at(-2).r, null);
assert.equal(chart.data.at(-1).r, 40);
chart.mark('pain', 2.05, 119);
assert.equal(chart.marks.at(-1).elevation, 119, 'chart flags retain the press-time angle independently of later live samples');
chart.push(2.1, 63, 40);
assert.equal(chart.marks.at(-1).elevation, 119);
const clusters = clusterMarkers([{ t: 1, type: 'pain' }, { t: 19, type: 'pain' }, { t: 19.5, type: 'click' }, { t: 20, type: 'pull' }], t => t * 10);
assert.deepEqual(clusters.map(c => c.marks.length), [1, 3], 'recent events collapse into a readable count instead of a pile at the edge');
chart.clear();
chart.push(10, 15, 0);
chart.push(14, 90, 20);
chart.ctx = new Proxy({}, { get: () => () => {} });
let plotted;
chart._line = (_key, _scale, X) => { plotted = chart.data.map(sample => X(sample.t)); };
chart._draw();
assert.equal(plotted[0], 34, 'short movement history starts at the left of the chart');
assert.equal(plotted[1], 290, 'initial test history uses the available width instead of a nearly empty twenty-second window');
console.log('timeline: loop restarts break both traces and reset smoothing');
